// Плаский порядок усіх пунктів шляху (урок → гра → задачі → наступний крок …)
export const FLOW = STEPS.flatMap(([, stepTitle, , links]) => links.map(([, title, href]) => ({ href, title: links.length > 1 ? `${stepTitle}: ${title}` : stepTitle })));

// Відмітити пункт як пройдений (href — від кореня сайту)
export function markSeen(href) {
  const LG = window.LG, seen = new Set(LG.store.get('path:seen', []));
  if (!seen.has(href)) { seen.add(href); LG.store.set('path:seen', [...seen]); }
}
// Наступний пункт шляху після href → { href (від кореня), title } або null
export function nextAfter(href) {
  const i = FLOW.findIndex(x => x.href === href);
  return i >= 0 && i < FLOW.length - 1 ? FLOW[i + 1] : null;
}
// Перейти до наступного пункту зі сторінки в підпапці (lessons/…)
export function goNext(href) {
  markSeen(href);
  const n = nextAfter(href);
  (window.LG && LG.go ? LG.go : h => { location.href = h; })('../' + (n ? (n.href.startsWith('#') ? 'index.html' + n.href : n.href) : 'index.html#learn'));
}
